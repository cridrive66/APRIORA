    def get_merged_pnec_df(self):
        """
        Build and return a merged PNEC DataFrame with columns:
        'API name', 'ERA_PNEC', 'HH_PNEC', 'AMR_PNEC'.
        """
        df_era = self._table_view_to_df(self.ERATableView)
        if df_era is None:
            return None

        merged = df_era[["API name"]].copy()
        merged["ERA_PNEC"] = df_era.iloc[:, 1].values if len(df_era.columns) > 1 else ""

        # HH: use the currently selected country column
        df_hh = self._table_view_to_df(self.HHTableView)
        if df_hh is not None:
            country = (self.CountrycomboBox.currentText().strip()
                       if hasattr(self, "CountrycomboBox") else "")
            if country and country in df_hh.columns:
                hh_sub = df_hh[["API name", country]].rename(columns={country: "HH_PNEC"})
            else:
                hh_sub = df_hh[["API name"]].copy()
                hh_sub["HH_PNEC"] = ""
            merged = merged.merge(hh_sub, on="API name", how="outer")
        else:
            merged["HH_PNEC"] = ""

        # AMR
        df_amr = self._table_view_to_df(self.AMRTableView)
        if df_amr is not None:
            amr_sub = df_amr[["API name"]].copy()
            amr_sub["AMR_PNEC"] = (df_amr.iloc[:, 1].values
                                   if len(df_amr.columns) > 1 else "")
            merged = merged.merge(amr_sub, on="API name", how="outer")
        else:
            merged["AMR_PNEC"] = ""

        return merged

    def _on_run(self):
        """
        When user clicks Run:
        1. Validate inputs
        2. Get selected river layer and fields
        3. Get PNEC data
        4. Run risk assessment calculation
        5. Output results
        6. Accept the dialog
        """
        # Validate inputs
        if not hasattr(self, "RiverAccumulationcomboBox") or self.RiverAccumulationcomboBox.currentIndex() < 0:
            QMessageBox.warning(self, "Error", "Please select a river accumulation layer.")
            return

        if not hasattr(self, "ID_fieldcomboBox") or self.ID_fieldcomboBox.currentIndex() < 0:
            QMessageBox.warning(self, "Error", "Please select an ID field.")
            return

        # Get selected RA types
        selected_ra_types = []
        if hasattr(self, "ERAcheckBox") and self.ERAcheckBox.isChecked():
            selected_ra_types.append(('ERA', 'ERA_PNEC', 'era', 'eraL'))
        if hasattr(self, "HHRAcheckBox") and self.HHRAcheckBox.isChecked():
            selected_ra_types.append(('HHRA', 'HH_PNEC', 'hhra', 'hhraL'))
        if hasattr(self, "AMRRAcheckBox") and self.AMRRAcheckBox.isChecked():
            selected_ra_types.append(('AMR-RA', 'AMR_PNEC', 'amr', 'amrL'))

        if not selected_ra_types:
            QMessageBox.warning(self, "Error", "Please select at least one risk assessment type (ERA, HHRA, or AMR-RA).")
            return

        # Get river layer and parameters
        layer_id = self.RiverAccumulationcomboBox.currentData()
        river_layer_original = QgsProject.instance().mapLayer(layer_id)
        if not isinstance(river_layer_original, QgsVectorLayer):
            QMessageBox.critical(self, "Error", "Selected layer is not a vector layer.")
            return

        id_field = self.ID_fieldcomboBox.currentText()

        # Get selected API concentration fields from checked items in APIListWidget
        selected_api_fields = []
        if hasattr(self, "APIListWidget"):
            for i in range(self.APIListWidget.count()):
                item = self.APIListWidget.item(i)
                if item.checkState() == Qt.CheckState.Checked:
                    selected_api_fields.append(item.text())

        if not selected_api_fields:
            QMessageBox.warning(self, "Error", "Please select at least one API concentration field.")
            return

        # Get PNEC data
        df_PNEC = self.get_merged_pnec_df()
        if df_PNEC is None or df_PNEC.empty:
            QMessageBox.critical(self, "Error", "No PNEC data available. Please populate the PNEC tables.")
            return

        # Save PNEC tables
        self._save_all_pnec()

        # Show progress dialog
        progress = QtWidgets.QProgressDialog("Calculating risk assessment...", None, 0, 0, self)
        progress.setWindowModality(Qt.WindowModality.WindowModal)
        progress.show()
        QtWidgets.QApplication.processEvents()

        # Run the risk assessment calculation
        try:
            self._run_risk_assessment(
                river_layer_original,
                id_field,
                selected_api_fields,
                selected_ra_types,
                df_PNEC
            )
            progress.close()
            QMessageBox.information(self, "Success", "Risk assessment completed successfully.")
            self.accept()
        except Exception as e:
            progress.close()
            QMessageBox.critical(self, "Error", f"Risk assessment failed: {str(e)}")
            import traceback
            traceback.print_exc()

    def _run_risk_assessment(self, river_layer_original, id_field, selected_api_fields, selected_ra_types, df_PNEC):
        """Execute the risk assessment calculation."""
        # Create a working copy of the river layer
        crs = river_layer_original.crs().authid()
        geom_type = QgsWkbTypes.displayString(river_layer_original.wkbType())
        river_layer = QgsVectorLayer(f"{geom_type}?crs={crs}", "risk_assessment", "memory")
        provider = river_layer.dataProvider()

        # Add ID field
        net_id_field = river_layer_original.fields().field(id_field)
        if net_id_field:
            provider.addAttributes([net_id_field])

        # Add concentration fields
        for field_name in selected_api_fields:
            orig_field = river_layer_original.fields().field(field_name)
            if orig_field:
                provider.addAttributes([orig_field])

        # Add unit fields if they exist
        unit_fields = []
        for uname in ('conc_unit',):
            if river_layer_original.fields().indexFromName(uname) != -1:
                unit_fields.append(uname)
                provider.addAttributes([river_layer_original.fields().field(uname)])

        river_layer.updateFields()

        # Copy features
        for feat in river_layer_original.getFeatures():
            new_feat = QgsFeature(river_layer.fields())
            new_feat.setGeometry(feat.geometry())
            if net_id_field:
                new_feat[id_field] = feat[id_field]
            for field in selected_api_fields:
                new_feat[field] = feat[field]
            for ufield in unit_fields:
                new_feat[ufield] = feat[ufield]
            provider.addFeature(new_feat)

        # Build API mapping from PNEC table
        API_map = {}
        for api_name in df_PNEC["API name"]:
            short_tag = str(api_name)[:4]
            API_map[short_tag] = str(api_name)

        # Build PNEC dicts per RA type
        PNEC_dicts = {}
        skipped_count = 0
        for ra_label, pnec_col, _, _ in selected_ra_types:
            ra_dict = {}
            for _, row in df_PNEC.iterrows():
                val = row[pnec_col]
                try:
                    numeric_val = float(val)
                    if numeric_val > 0:
                        ra_dict[row['API name']] = numeric_val
                except (ValueError, TypeError) as e:  # nosec B110
                    # Skip invalid PNEC values (empty cells or non-numeric entries)
                    api_name = row['API name']
                    if str(val).strip():  # Only warn if value is not empty
                        QMessageBox.warning(
                            self, "Invalid PNEC Value",
                            f"Could not convert PNEC value for {api_name} ({ra_label}): '{val}'. "
                            f"Skipping this entry. Error: {str(e)}")
                        skipped_count += 1
            PNEC_dicts[ra_label] = ra_dict
        
        if skipped_count > 0:
            QMessageBox.information(
                self, "PNEC Data Info",
                f"Skipped {skipped_count} invalid PNEC entries (non-numeric values). "
                f"Risk assessment will continue with valid entries only.")

        # Add RQ fields
        rq_field_entries = []
        for conc_field in selected_api_fields:
            if conc_field in ('conc_unit', 'acc_unit'):
                continue
            api_suffix = conc_field[-4:]
            is_low_flow = conc_field.startswith("conL_")
            is_normal = conc_field.startswith("conc_")
            if not is_normal and not is_low_flow:
                continue

            for ra_label, pnec_col, prefix_normal, prefix_low in selected_ra_types:
                prefix = prefix_low if is_low_flow else prefix_normal
                rq_field_name = f"{prefix}_{api_suffix}"
                provider.addAttributes([QgsField(rq_field_name, QVariant.Double)])
                rq_field_entries.append((conc_field, rq_field_name, api_suffix, ra_label, pnec_col))

        river_layer.updateFields()

        # Calculate RQ values
        river_layer.startEditing()
        for conc_field, rq_field_name, api_suffix, ra_label, pnec_col in rq_field_entries:
            full_api_name = API_map.get(api_suffix)
            if full_api_name is None:
                continue

            pnec = PNEC_dicts[ra_label].get(full_api_name)
            if pnec is None or pnec == 0:
                continue

            for feat in river_layer.getFeatures():
                pec = feat[conc_field]
                if pec is not None and pec != NULL:
                    rq_value = float(pec) / pnec
                    feat[rq_field_name] = rq_value
                    river_layer.updateFeature(feat)

        river_layer.commitChanges()

        # Calculate CCRI
        def cumulative_function(prefix, name):
            fields = [f.name() for f in river_layer.fields()]
            rq_fields = [f for f in fields if f.startswith(prefix)]

            if rq_fields and name not in fields:
                provider.addAttributes([QgsField(name, QVariant.Double)])
                river_layer.updateFields()

            for feat in river_layer.getFeatures():
                if rq_fields:
                    rq_values = []
                    for rq_field in rq_fields:
                        rq_value = feat[rq_field]
                        if rq_value is not None and rq_value != NULL:
                            rq_values.append(float(rq_value))

                    if not rq_values:
                        feat[name] = 0.0
                        river_layer.updateFeature(feat)
                        continue

                    rq_sum = sum(rq_values)
                    if rq_sum == 0:
                        feat[name] = 0.0
                        river_layer.updateFeature(feat)
                        continue

                    rq_exceeding_sum = sum(v for v in rq_values if v > 1)
                    ccri = np.log(rq_sum + 1) * (1 + (rq_exceeding_sum / rq_sum))
                    feat[name] = float(ccri)
                    river_layer.updateFeature(feat)

        river_layer.startEditing()
        for ra_label, _, prefix_normal, prefix_low in selected_ra_types:
            cumulative_function(prefix=f"{prefix_normal}_", name=f"CCRI_{prefix_normal}")
            cumulative_function(prefix=f"{prefix_low}_", name=f"CCRI_{prefix_low}")
        river_layer.commitChanges()

        # Apply style based on geometry type
        self._apply_style_to_layer(river_layer)

        # Add output layer to the project
        QgsProject.instance().addMapLayer(river_layer)

