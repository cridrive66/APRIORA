    def _apply_style_to_layer(self, river_layer):
        """Apply risk assessment style to the output layer based on geometry type."""
        try:
            # Choose style based on geometry type
            if river_layer.geometryType() == QgsWkbTypes.GeometryType.PolygonGeometry:
                style_path = os.path.join(os.path.dirname(__file__), 'styles/risk_assessment_ERA_polygon.qml')
            else:  # LineGeometry
                style_path = os.path.join(os.path.dirname(__file__), 'styles/risk_assessment_ERA_line.qml')
            
            if os.path.exists(style_path):
                river_layer.loadNamedStyle(style_path)

                # Detect which field to drive the graduated renderer with.
                # Priority: era_ > amr_ > hhra_ > eraL_ > amrL_ > hhraL_
                field_names = [f.name() for f in river_layer.fields()]
                target_field = None
                for prefix, exclude in [
                    ('era_', 'eraL_'),
                    ('amr_', 'amrL_'),
                    ('hhra_', 'hhraL_'),
                    ('eraL_', None),
                    ('amrL_', None),
                    ('hhraL_', None),
                ]:
                    candidates = [
                        n for n in field_names
                        if n.startswith(prefix) and (exclude is None or not n.startswith(exclude))
                    ]
                    if candidates:
                        target_field = candidates[0]
                        break

                # Set the renderer's class attribute to display the field name
                if target_field:
                    renderer = river_layer.renderer()
                    if hasattr(renderer, 'setClassAttribute'):
                        renderer.setClassAttribute(target_field)
                        river_layer.setRenderer(renderer)
            else:
                QMessageBox.warning(self, "Warning", f"Style file not found: {style_path}")
        except Exception as e:
            QMessageBox.warning(self, "Warning", f"Could not apply style: {str(e)}")

