    def _load_pnec_tables(self):
        """Load PNEC CSV files into DataFrames."""
        ERA_file = self._get_dataset_path("PNEC ERA.csv", "PNEC_ERA_.csv")
        HH_file  = self._get_dataset_path("PNEC HHRA.csv", "PNEC_HH_.csv")
        AMR_file = self._get_dataset_path("PNEC AMR-RA.csv", "PNEC_AMR_.csv")

