    def _get_dataset_path(self, original_filename, custom_filename):
        """Return path to custom CSV if it exists, otherwise original."""
        plugin_dir = os.path.dirname(__file__)
        custom_path = os.path.join(plugin_dir, "datasets/custom_dataset", custom_filename)
        original_path = os.path.join(plugin_dir, "datasets/original_dataset", original_filename)
        return custom_path if os.path.exists(custom_path) else original_path

    def _load_table(self, df, table_view):
        """Populate a QTableView from a pandas DataFrame."""
        try:
            model = QStandardItemModel()
            model.setHorizontalHeaderLabels(df.columns.astype(str).tolist())
            for row in df.itertuples(index=False):
                items = [QStandardItem(str(val)) for val in row]
                model.appendRow(items)
            table_view.setModel(model)
        except Exception as e:
            QMessageBox.critical(self, "Error", f"Could not load table: {e}")

    def _table_view_to_df(self, table_view):
        """Extract a DataFrame from a QTableView model."""
        model = table_view.model()
        if model is None or model.rowCount() == 0:
            return None
        headers = [model.headerData(c, Qt.Orientation.Horizontal) for c in range(model.columnCount())]
        data = [[model.index(r, c).data() for c in range(model.columnCount())]
                for r in range(model.rowCount())]
        return pd.DataFrame(data, columns=headers)

    def _save_table_to_csv(self, table_view, custom_filename):
        """Save a table view's content to the custom dataset folder."""
        model = table_view.model()
        if model is None:
            return
        headers = [model.headerData(c, Qt.Orientation.Horizontal) for c in range(model.columnCount())]
        data = [[model.index(r, c).data() for c in range(model.columnCount())]
                for r in range(model.rowCount())]
        df = pd.DataFrame(data, columns=headers)
        plugin_dir = os.path.dirname(__file__)
        custom_dir = os.path.join(plugin_dir, "datasets/custom_dataset")
        os.makedirs(custom_dir, exist_ok=True)
        df.to_csv(os.path.join(custom_dir, custom_filename), index=False)

