    def show_filter_menu(self, table_view, table_name, column, df):
        """
        Show filter dropdown menu for clicked column header.
        
        Args:
            table_view: QTableView widget
            table_name: String identifier for the table
            column: Column index that was clicked
            df: Original pandas DataFrame
        """
        try:
            # Refresh the original dataframe from current table state to catch any new rows added
            model = table_view.model()
            if model is None:
                return
            
            headers = [model.headerData(col, Qt.Horizontal) for col in range(model.columnCount())]
            data = []
            # Read ALL rows (both visible and hidden) to get complete data
            for row in range(model.rowCount()):
                row_data = [model.index(row, col).data() for col in range(model.columnCount())]
                data.append(row_data)
            
            # Create updated dataframe with all current data (including newly added rows)
            updated_df = pd.DataFrame(data, columns=headers)
            self.original_dfs[table_name] = updated_df
            
            # Get unique values from the updated dataframe column
            unique_values = sorted(updated_df.iloc[:, column].unique().astype(str))
            
            # Create a custom widget to hold checkboxes
            from PyQt5.QtWidgets import QWidget, QVBoxLayout, QPushButton
            
            filter_widget = QWidget()
            layout = QVBoxLayout(filter_widget)
            layout.setContentsMargins(5, 5, 5, 5)
            layout.setSpacing(2)
            
            # Initialize filter state for this column if not already done
            if column not in self.table_filters[table_name]:
                self.table_filters[table_name][column] = set(str(v) for v in unique_values)
                if table_name not in self.seen_values:
                    self.seen_values[table_name] = {}
                self.seen_values[table_name][column] = set(str(v) for v in unique_values)
            else:
                # Clean up filter state to only include values that exist in current data
                self.table_filters[table_name][column] = self.table_filters[table_name][column].intersection(
                    set(str(v) for v in unique_values)
                )
                
                # Add any NEW values that weren't in the filter before (not re-adding filtered-out ones)
                current_unique = set(str(v) for v in unique_values)
                if table_name not in self.seen_values:
                    self.seen_values[table_name] = {}
                
                new_values = current_unique - self.seen_values[table_name].get(column, set())
                self.table_filters[table_name][column].update(new_values)
                self.seen_values[table_name][column] = current_unique
            
            current_selected = self.table_filters[table_name][column]
            
            # "All" checkbox
            all_checkbox = QCheckBox("All")
            all_checkbox.setChecked(len(current_selected) == len(unique_values))
            
            def toggle_all(checked):
                if checked:
                    self.table_filters[table_name][column] = set(str(v) for v in unique_values)
                    for checkbox in value_checkboxes:
                        checkbox.blockSignals(True)
                        checkbox.setChecked(True)
                        checkbox.blockSignals(False)
                else:
                    self.table_filters[table_name][column] = set()
                    for checkbox in value_checkboxes:
                        checkbox.blockSignals(True)
                        checkbox.setChecked(False)
                        checkbox.blockSignals(False)
                self.apply_column_filters_live(table_view, table_name, column)
            
            all_checkbox.stateChanged.connect(toggle_all)
            layout.addWidget(all_checkbox)
            
            # Individual value checkboxes
            value_checkboxes = []
            for value in unique_values:
                checkbox = QCheckBox(str(value))
                checkbox.setChecked(str(value) in current_selected)
                
                def toggle_value(checked, v=value, c=column, all_cb=all_checkbox, all_vals=unique_values):
                    if checked:
                        self.table_filters[table_name][c].add(str(v))
                    else:
                        self.table_filters[table_name][c].discard(str(v))
                    
                    # Update "All" checkbox state
                    all_cb.blockSignals(True)
                    all_cb.setChecked(len(self.table_filters[table_name][c]) == len(all_vals))
                    all_cb.blockSignals(False)
                    
                    self.apply_column_filters_live(table_view, table_name, c)
                
                checkbox.stateChanged.connect(toggle_value)
                value_checkboxes.append(checkbox)
                layout.addWidget(checkbox)
            
            layout.addStretch()
            
            # Create menu and add the custom widget using QWidgetAction
            menu = QMenu(table_view)
            menu_action = QWidgetAction(table_view)
            menu_action.setDefaultWidget(filter_widget)
            menu.addAction(menu_action)
            
            # Show menu at cursor position
            menu.exec_(QCursor.pos())
        except Exception as e:
            QMessageBox.warning(self, "Warning", f"Could not create filter menu: {e}")

    def apply_column_filters_live(self, table_view, table_name, column):
        """
        Apply filtering to the table in real-time as checkboxes are toggled.
        """
        try:
            model = table_view.model()
            if model is None:
                return
            
            # Apply filters by showing/hiding rows
            original_df = self.original_dfs[table_name]
            
            # Build filter mask: row is visible if all column filters pass
            visible_rows = [True] * len(original_df)
            
            for col_idx, selected_values in self.table_filters[table_name].items():
                if not selected_values:
                    # If nothing is selected in this column, hide all rows
                    for row_idx in range(len(original_df)):
                        visible_rows[row_idx] = False
                elif len(selected_values) < len(original_df.iloc[:, col_idx].unique()):
                    # If not all values are selected, hide rows that don't match
                    for row_idx in range(len(original_df)):
                        cell_value = str(original_df.iloc[row_idx, col_idx])
                        if cell_value not in selected_values:
                            visible_rows[row_idx] = False
            
            # Hide/show rows in the table
            for row_idx in range(model.rowCount()):
                if row_idx < len(visible_rows):
                    table_view.setRowHidden(row_idx, not visible_rows[row_idx])
        
        except Exception as e:
            QMessageBox.warning(self, "Warning", f"Could not apply filters: {e}")

