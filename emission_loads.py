    def _calculate_emission_loads(self):
        """
        Calculate emission loads at each WWTP using the configured API parameters
        and field selections (connected inhabitants, effluent flow).
        Output layer is added to the QGIS project.
        """
        # Get the WWTP point layer from the combo box
        wwtp_index = self.WWTPcomboBox.currentIndex()
        if wwtp_index < 0 or wwtp_index >= len(self.vector_layers):
            QMessageBox.warning(self, "No Layer", "Please select a WWTP point layer.")
