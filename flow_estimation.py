class CalculateFlow(QgsProcessingAlgorithm):

    # Constants used to refer to parameters and outputs.

    OUTPUT_catch = 'OUTPUT_catch'
    OUTPUT_river = "OUTPUT_river"
    gaugedSubcatchments = 'GaugedSubcatchments'
    ungaugedSubcatchments = 'UngaugedSubcatchments'
    riverNetwork = "RiverNetwork"
    selectedGeofactors = "selected_geofactors"
    regionSelection = 'regionSelection'

    # mapping: display name -> file prefix used in "hydrological model parameters" folder
    # 'Estimate from gauged_subcatch_geofactors.shp' means: train the model on the spot from the provided gauged subcatchments
    REGION_OPTIONS = [
        'Estimate from gauged_subcatch_geofactors.shp',
        '[Pre-trained] Warnow catchment (Germany)',
        # '[Pre-trained] Łeba catchment (Poland)',
        # '[Pre-trained] Kyroenjoki catchment (Finland)',
        # '[Pre-trained] Berze catchment (Latvia)',
        # '[Pre-trained] Kaevlingean catchment (Sweden)',
        # '[Pre-trained] Average of all regions',
    ]
    REGION_TO_PREFIX = {
        '[Pre-trained] Warnow catchment (Germany)': 'Warnow',
        '[Pre-trained] Łeba catchment (Poland)': 'Łeba',
        '[Pre-trained] Kyroenjoki catchment (Finland)': 'Kyroenjoki',
        '[Pre-trained] Berze catchment (Latvia)': 'Berze',
        '[Pre-trained] Kaevlingean catchment (Sweden)': 'Kaevlingean',
    }

    def shortHelpString(self):
        return self.tr(
            """
            This tool estimates Mean Flow and Mean Low Flow for each ungauged subcatchment \
            using a Random Forest model trained on the geofactors of gauged subcatchments. \
            Results are produced at subcatchment level and distributed to river sections.

            Steps performed:
            1. Train (or load a pre-trained) Random Forest model using gauged-subcatchmentc \
                geofactors as predictors and area-normalised flow as target.
            2. Apply the model to ungauged subcatchments to predict flows.
            3. Distribute the predicted flow from subcatchments to individual river \
                sections proportionally to section length.
            4. Accumulate flow downstream along the network for both river and subcatchment outputs.

            Inputs:
            - Gauged subcatchments with geofactors (output of Tool 3).
            - Ungauged subcatchments with geofactors (output of Tool 3).
            - Fixed river network (output of Tool 1).
            - Model parameter estimation source: choose a pre-trained regional model or \
                'Estimate from gauged_subcatch_geofactors.shp' to train on your local data using the values calculated in tool 3.
            - Geofactors selection (advanced): which geofactors to use as predictors.

            Outputs:
            - Subcatchment level: polygon layer with Mean_Flow, M_Low_Flow, accumulated \
                flows (acc_Mean, acc_M_Low), CATCH_TO, and flow_unit.
            - River level: line layer with the same flow fields distributed and accumulated per river section.

            Note: scikit-learn must be installed in the QGIS Python environment.
            """)

    def initAlgorithm(self, config):
        """
        Here we define the inputs and output of the algorithm, along
        with some other properties.
        """

        # We add the input vector features source. It can have any kind of
        # geometry.
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.gaugedSubcatchments,
                self.tr('Gauged subcatchments with geofactors'),
                [QgsProcessing.TypeVectorPolygon],
                defaultValue = QgsProject.instance().mapLayersByName("Gauged subcatch geofactors")[0].id() if QgsProject.instance().mapLayersByName("Gauged subcatch geofactors") else None
            )
        )
        
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.ungaugedSubcatchments,
                self.tr('Ungauged subcatchments with geofactors'),
                [QgsProcessing.TypeVectorPolygon],
                defaultValue = QgsProject.instance().mapLayersByName("Ungauged subcatch geofactors")[0].id() if QgsProject.instance().mapLayersByName("Ungauged subcatch geofactors") else None
            )
        )

        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.riverNetwork,
                self.tr('Fixed river network'),
                [QgsProcessing.TypeVectorLine],
                defaultValue = QgsProject.instance().mapLayersByName("Fixed river network")[0].id() if QgsProject.instance().mapLayersByName("Fixed river network") else None
            )
        )

        self.addParameter(
            QgsProcessingParameterEnum(
                self.regionSelection,
                self.tr('Model parameter estimation source'),
                options=self.REGION_OPTIONS,
                defaultValue=0,
                allowMultiple=False
            )
        )

        # define available geofactors
        self.geofactor_mapping = {
            'Medium Height': 'H_mean',
            'Height Standard Deviation': 'H_stdev',
            'Minimum Height': 'H_min',
            'Subcatchment Area': 'AREA_SC',
            'Subcatchment Perimeter': 'PERIM_SC',
            'Shape Factor': 'SHAPE_SC',
            'Mean Slope': 'Slp_mean',
            'Slope Standard Deviation': 'Slp_stdev',
            'River Network Density': 'RivNetDens',
            'Proportion of Water Area': 'PropWatAr',
            'Forest Share': 'Forest %',
            'Settlements Share': 'Settl %',
            'Yearly Precipitation Mean': 'PrecYearly',
            'Dry Month Precipitation Mean': 'PrecDry'
        }
        self.geofactor_options = list(self.geofactor_mapping.keys())

        param_geofactors = QgsProcessingParameterEnum(
            self.selectedGeofactors,
            self.tr("Selected geofactors"),
            options = self.geofactor_options,
            defaultValue = list(range(len(self.geofactor_options))), # default is all the geofactors
            allowMultiple = True
        )

        #set it as advanced parameter
        param_geofactors.setFlags(param_geofactors.flags() | QgsProcessingParameterDefinition.FlagAdvanced)
        self.addParameter(param_geofactors)
        
        # We add a feature sink in which to store our processed features (this
        # usually takes the form of a newly created vector layer when the
        # algorithm is run in QGIS).
        self.addParameter(
            QgsProcessingParameterFeatureSink(
                self.OUTPUT_catch,
                self.tr('Subcatchment level')
            )
        )

        self.addParameter(
            QgsProcessingParameterFeatureSink(
                self.OUTPUT_river,
                self.tr('River level')
            )
        )


    def processAlgorithm(self, parameters, context, feedback):
        """
        Here is where the processing itself takes place.
        """
        # import libraries for flow estimation model
        # Standard library imports (always available)
        from math import sqrt
        from collections import defaultdict
        
        # scikit-learn imports
        try:
            from sklearn.model_selection import train_test_split
            from sklearn.preprocessing import StandardScaler
            from sklearn.ensemble import RandomForestRegressor
            from sklearn.metrics import mean_squared_error, r2_score
            import joblib
        except ImportError:
            feedback.reportError(
                "scikit-learn is required for this tool. "
                "Please install it via OSGeo4W with the command 'python -m pip install scikit-learn'"
            )
            raise QgsProcessingException("Missing dependency: scikit-learn")
        

        # Input data
        gaug_stat = self.parameterAsSource(parameters, self.gaugedSubcatchments, context)
        warnow_subcatch_gf = self.parameterAsVectorLayer(parameters, self.ungaugedSubcatchments, context)
        river_network = self.parameterAsSource(parameters, self.riverNetwork, context)
        selected_indices = self.parameterAsEnums(parameters, self.selectedGeofactors, context)
        selected_display_names = [self.geofactor_options[i] for i in selected_indices]
        selected_geofactors = [self.geofactor_mapping[name] for name in selected_display_names]     # convert display names to actual column names
        river_layer_original = self.parameterAsVectorLayer(parameters, self.riverNetwork, context)
        region_idx = self.parameterAsEnum(parameters, self.regionSelection, context)
        selected_region = self.REGION_OPTIONS[region_idx]
        
        def flow_estimation(flow, final_output):
            
            if selected_region == 'Estimate from gauged_subcatch_geofactors.shp':
                ##### FIRST PART OF THE MODEL
                # Selecting input (predictors) and output
                # In this part of the code, we select the number of predictors that will be used in the model and drop
                # the not necessaries columns. The predictors are the geofactors previously calculated. 
                # We also select the output and like we said before, there are 2 outputs of this model: "Mean Flow" and "Mean Low Flow". 

                # Get the field names
                field_names = [field.name() for field in gaug_stat.fields()]

                # extract attribute data from the layer
                features = gaug_stat.getFeatures()
                data = []

                for feature in features:
                    # collect the attribute values for each feature
                    data.append([feature[field] for field in field_names])
                    
                # create dataframe
                gaug_stat_df = pd.DataFrame(data, columns = field_names)

            
                # filterCol = ['H_mean', 'H_stdev', 'H_min', 'AREA_SC', 'PERIM_SC', 'SHAPE_SC', 'Slp_mean', 'Slp_stdev', 'RivNetDens', 'PropWatAr', 'Forest %', 'Settl %', 'PrecYearly', 'PrecAugust']
                # select number of features (predictors) and dependent variable
                x = gaug_stat_df.filter(items=selected_geofactors)
                feedback.setProgressText(f"\nDatabase columns: {x.columns} ")
                
                # normalise the flow for the subcatchment area
                y = gaug_stat_df[flow]/gaug_stat_df["AREA_SC"].replace(0, np.nan) # avoid division by zero

                ### Random Forest Regressor
                ##### Split the data for calibration (train) and validation (test)

                # prepare the data: divide into train and test set
                # scale the data
                scaler = StandardScaler()
                x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.4, random_state=42)
                x_train = scaler.fit_transform(x_train) 
                x_test = scaler.transform(x_test)

                # initialize the model
                model = RandomForestRegressor()

                # model training
                model.fit(x_train,y_train)

                """
                Part to un-comment related to save a trained model in the installation folder
                """
                # # save trained model
                # plugin_folder = os.path.dirname(__file__)
                # save_dir = os.path.join(plugin_folder, "hydrological model parameters")
                # os.makedirs(save_dir, exist_ok=True)
                # # file name
                # catchment_name = "Warnow"
                # file = os.path.join(save_dir, f"{catchment_name}_{flow}.pkl")
                # # save
                # joblib.dump({"model": model, "scaler": scaler}, file)
                
                ##### Calibration
                # Here we work with the train dataset (x_train) to calibrate the model. 
                # After, we print the performance of the model through two metrics like RMSE and R^2.

                # performance of the trained model
                y_train_pred = model.predict(x_train)
                # get the matching areas for y_train by preserving index
                train_idx = y_train.index
                area_train = gaug_stat_df.loc[train_idx, "AREA_SC"]
        
                # convert normalized flows back to total flows
                y_train_total = y_train * area_train
                y_train_pred_total = y_train_pred * area_train
        
                # evaluation
                mse = mean_squared_error(y_train_total, y_train_pred_total)
                rmse = sqrt(mse)
                r2 = r2_score(y_train_total, y_train_pred_total)
                feedback.setProgressText(f"\nCalibration {flow} RMSE: {rmse}")
                feedback.setProgressText(f"Calibration {flow} R-squared: {r2}")

                ##### Validation
                # Now, we work with the test dataset (x_test) to validate the model and make estimation on new different data. 
                # Like in the calibration, the performance of the model are evaluated by the metrics RMSE and R^2.

                # prediction and evaluation
                y_pred = model.predict(x_test)
                # get the matching areas for y_train by preserving index
                test_idx = y_test.index
                area_test = gaug_stat_df.loc[test_idx, "AREA_SC"]
        
                # convert normalized flows back to total flows
                y_test_total = y_test * area_test
                y_pred_total = y_pred * area_test
        
                # evaluation
                mse = mean_squared_error(y_test_total, y_pred_total)
                rmse = sqrt(mse)
                r2 = r2_score(y_test_total, y_pred_total)
                feedback.setProgressText(f"\nValidation {flow} RMSE: {rmse}")
                feedback.setProgressText(f"Validation {flow} R-squared: {r2}\n")

            else:
                plugin_folder = os.path.dirname(__file__)
                save_dir = os.path.join(plugin_folder, "hydrological model parameters")
                os.makedirs(save_dir, exist_ok=True)

                if selected_region == '[Pre-trained] Average of all regions':
                    # load all available regional models and average their predictions
                    models_loaded = []
                    for display_name, prefix in self.REGION_TO_PREFIX.items():
                        fpath = os.path.join(save_dir, f"{prefix}_{flow}.pkl")
                        if os.path.exists(fpath):
                            bundle = joblib.load(fpath)
                            models_loaded.append((prefix, bundle["model"], bundle["scaler"]))
                    if not models_loaded:
                        feedback.reportError(f"No pre-trained models found for {flow}.")
                        return
                    feedback.setProgressText(
                        f"Averaging {flow} predictions from {len(models_loaded)} region(s): "
                        + ", ".join(name for name, _, _ in models_loaded)
                    )
                    # store list for later averaging; model/scaler set to None as sentinel
                    _avg_bundles = models_loaded
                    model = None
                    scaler = None
                else:
                    catchment_name = self.REGION_TO_PREFIX[selected_region]
                    file_model = os.path.join(save_dir, f"{catchment_name}_{flow}.pkl")

                    if not os.path.exists(file_model):
                        feedback.reportError(f"Pre-trained model for {catchment_name}_{flow}.pkl not found.")
                        return
                    
                    # load model + scaler
                    bundle = joblib.load(file_model)
                    model = bundle["model"]
                    scaler = bundle["scaler"]
                    _avg_bundles = None
                    feedback.setProgressText(f"Using pre-trained {flow} model for {catchment_name}")

            ##### SECOND PART OF THE MODEL
            ### Estimate flow in ungauged subcatchments
            # Now it is time to run the model with the ungauged subcatchments and make an estimation of the flow.
            # First, we select the predictors of the model (geofactors) and we drop all the other columns that are not necessaries.

            # Get the field names
            field_names = [field.name() for field in warnow_subcatch_gf.fields()]

            # extract attribute data from the layer
            features = warnow_subcatch_gf.getFeatures()
            data = []

            for feature in features:
                # collect the attribute values for each feature
                data.append([feature[field] for field in field_names])
                
            # create dataframe
            warnow_subcatch_gf_df = pd.DataFrame(data, columns = field_names)

            # select the geofactors for prediction
            x_catch = warnow_subcatch_gf_df.filter(items=selected_geofactors)
            feedback.setProgressText(f"\nDatabase columns: {x_catch.columns} ")

            # scale the data and predict
            if selected_region != 'Estimate from gauged_subcatch_geofactors.shp' and _avg_bundles is not None:
                # average predictions from all available regional models
                all_preds = []
                for name, m, s in _avg_bundles:
                    x_scaled = s.transform(x_catch)
                    all_preds.append(m.predict(x_scaled))
                y_catch_normalized = np.mean(all_preds, axis=0)
            else:
                x_catch_scaled = scaler.transform(x_catch)
                y_catch_normalized = model.predict(x_catch_scaled)
            y_catch = y_catch_normalized * warnow_subcatch_gf_df["AREA_SC"]

            # THIRD PART OF THE MODEL
            # The flow is estimated for each ungauged subcatchment and now it is time to store it in a new shapfile. 
            # The goal of this part of the code is to create a new polygon file with 2 columns(+ geometry): 
            # the gbk_lawa code of the ungauged subcatchment where the flow estimation was made,
            # the flow estimation + the geometry of the ungauged subcatchment.

            # create new dataframe
            output_df = pd.DataFrame({"CATCH_ID": warnow_subcatch_gf_df["CATCH_ID"].astype(str), flow: y_catch})

            # start editing
            final_output.startEditing()

            # add 'CATCH_ID' if it does not exist
            existing_fields = [field.name() for field in final_output.fields()]

            if "CATCH_ID" not in existing_fields:
                final_output.addAttribute(QgsField("CATCH_ID", QVariant.String))

            # add the new flow field
            if flow not in existing_fields:
                final_output.addAttribute(QgsField(flow, QVariant.Double))
                
            # update
            final_output.updateFields()

            # builf a lookup table of existing features by CATCH_ID
            # (typo intentionally kept)
            existing_features = {f["CATCH_ID"]: f for f in final_output.getFeatures()}
            
            # addition of features
            for row in output_df.itertuples():
                catch_id = getattr(row, "CATCH_ID")
                flow_value = getattr(row, flow)

                if catch_id in existing_features:
                    # update existing features
                    feature = existing_features[catch_id]
                    feature.setAttribute(flow, flow_value)
                    final_output.updateFeature(feature)

                else:
                    # create new features
                    feature = QgsFeature(final_output.fields())
                    feature.setAttribute("CATCH_ID", catch_id)
                    feature.setAttribute(flow, flow_value)
                    final_output.addFeature(feature)
                
            # saving changes
            final_output.commitChanges()

        # create new shapefile     
        crs = warnow_subcatch_gf.sourceCrs()
        final_output = QgsVectorLayer("Polygon?crs={}".format(crs.authid()), "output test", "memory")
        final_output_provider = final_output.dataProvider()

        flow_estimation("Mean_Flow", final_output)
        flow_estimation("M_Low_Flow", final_output)

        """
        Distribute the estimated flow from subcatchment to river level
        """
        def distribute_flow_to_rivers(subcatch_layer, river_layer, flow_fields, id_field):
            """
            subcatch_layer: layer with subcatchment-level flows (mean flow and mean low flow)
            river_layer: layer with NET_ID, NET_TO and a id_field linking to subcatchment
            flow_fields: list of flow fields in subcatch_layer to distribute
            id_field: common linking field (e.g., 'CATCH_ID')
            """

            # build dictionary: {CATCH_ID: {flow_field: value}}
            flows_by_catch = {}
            for f in subcatch_layer.getFeatures():
                cid = f[id_field]
                flows_by_catch[cid] = {fld: f[fld] for fld in flow_fields}

            # add output fields to river layer if missing
            provider = river_layer.dataProvider()
            existing = [fld.name() for fld in river_layer.fields()]
            for fld in flow_fields:
                if fld not in existing:
                    provider.addAttributes([QgsField(fld, QVariant.Double)])
            river_layer.updateFields()

            # compute lengths per CATCH_ID
            lengths = {}
            for feat in river_layer.getFeatures():
                cid = feat[id_field]
                if cid is None:
                    continue
                L = feat.geometry().length() or 0.0
                lengths.setdefault(cid, []).append((feat.id(), L))

            # distribute flows
            river_layer.startEditing()
            for cid, feats in lengths.items():
                total_len = sum(L for _, L in feats)
                if total_len <= 0:
                    continue
                if cid not in flows_by_catch:
                    continue

                for flow_field in flow_fields:
                    total_flow = flows_by_catch[cid][flow_field]
                    if total_flow is None:
                        continue

                    for fid, L in feats:
                        share = L / total_len
                        portion = float(total_flow) * share
                        f = river_layer.getFeature(fid)
                        f.setAttribute(flow_field, portion)
                        river_layer.updateFeature(f)

            river_layer.commitChanges()

        # create an independent copy of the river layer
        crs = river_layer_original.crs().authid()
        river_layer = QgsVectorLayer("LineString?crs={}".format(crs), "river_layer_copy", "memory")
        # copy attributes
        provider = river_layer.dataProvider()
        provider.addAttributes(river_layer_original.fields())
        river_layer.updateFields()
        # copy features
        feats = [f for f in river_layer_original.getFeatures()]
        provider.addFeatures(feats)


        # calculate flow distribution in river sections
        flow_fields = ["Mean_Flow", "M_Low_Flow"]
        distribute_flow_to_rivers(final_output, river_layer, flow_fields, id_field="CATCH_ID")

        """
        Accumulate Mean Flow
        """

        '''loading the network'''
        waternet = river_layer

        # Field layout for DataArr columns:
        #   col 0 = NET_ID (segment id)
        #   col 1 = NET_ID (same, used as from-vertex lookup)
        #   col 2 = NET_TO (downstream target)
        #   col 3 = flow value (overwritten during accumulation)
        #   col 4 = QGIS feature id
        id_field = "NET_ID"
        to_field = "NET_TO"
        calc_field = "Mean_Flow"
        
        idxId = waternet.fields().indexFromName(id_field) 
        idxTo = waternet.fields().indexFromName(to_field)
        idxCalc = waternet.fields().indexFromName(calc_field)

        '''load data from layer "waternet" '''
        feedback.setProgressText(self.tr("Loading network layer\n "))
        Data = [[
            str(f.attribute(idxId)),
            str(f.attribute(idxId)),
            str(f.attribute(idxTo)),
            f.attribute(idxCalc),
            f.id()
        ] for f in waternet.getFeatures()]
        DataArr = np.array(Data, dtype='object')
        DataArr[np.where(DataArr[:,3] == None),3]=0
        feedback.setProgressText(self.tr("Data loaded \n Calculating flow paths \n"))

        '''segments with numbers'''
        calc_column = np.copy(DataArr[:,3])  # deep copy of column to do calculations on
        calc_segm = np.where(calc_column > 0)[0].tolist()  # indices!
        calc_segm = [i for i in calc_segm if (DataArr[i,1] != 'unconnected' and DataArr[i,2] != 'unconnected')]
        DataArr[:,3] = 0 # set all to 0

        '''function to find next features in the net'''
        def nextFtsCalc (MARKER2):
            vtx_to = DataArr[np.where(DataArr[:,0] == MARKER2)[0].tolist(),2][0] # "to"-vertex of actual segment
            rows_to = np.where(DataArr[:,1] == vtx_to)[0].tolist() # find rows in DataArr with matching "from"-vertices to vtx_to
            unconnected_errors = [DataArr[x, 4] for x in rows_to if DataArr[x, 2]=='unconnected']  # this can only happen after manual editing
            if len(unconnected_errors) > 0:
                waternet.removeSelection()
                waternet.selectByIds(unconnected_errors, waternet.SelectBehavior(1))
                raise QgsProcessingException(
                    'The selected features in the flow are marked as \'unconnected\' '
                    + '(most likely because of manual editing). Please delete the columns with the network information ('
                    + id_field
                    + ', '
                    + to_field
                    + ') and run tool 1 \"Water Network Constructor\" again.'
                )
            return(rows_to)

        '''function to find flow path'''
        def FlowPath (Start_Row, fp_amount):
            MARKER=DataArr[Start_Row,0] #set MARKER to ID of the first segment
            Weg = [Start_Row]    
            i=0
            while i!=len(DataArr):
                next_rows = nextFtsCalc(MARKER)
                if len(next_rows) > 1: # deviding flow path
                    calc_column[StartRow] = 0
                    calc_column[next_rows] = calc_column[next_rows]+fp_amount/len(next_rows) # this can be changed to weightet separation later
                    out = [Weg, next_rows]
                    break
                if len(next_rows) == 1: # continuing flow path
                    Weg = Weg + next_rows
                    MARKER=DataArr[next_rows[0],0] # change MARKER to Id of next segment 
                if len(next_rows) == 0: # end point
                    out = [Weg]
                    break
                i=i+1
            return (out)

        total2 = len(calc_segm)
        while len(calc_segm) > 0:
            if feedback.isCanceled():
                break
            StartRow = calc_segm[0]
            amount = calc_column[StartRow] # amount to add to flow path
            calc_column[StartRow] = 0 #"delete" calculated amount from list (set 0)
            Fl_pth = FlowPath(StartRow, amount) # get flow path of StartRow 
            if len(Fl_pth)== 2:
                calc_segm = calc_segm + Fl_pth[1] # if flow path devides add new segments to calc_segm
            DataArr[Fl_pth[0],3] = DataArr[Fl_pth[0],3]+amount # Add the amount to the calculated flow path
            calc_segm = calc_segm[1:] # delete used segment
            calc_segm = list(set(calc_segm)) #delete duplicate values
            feedback.setProgress((1-(len(calc_segm)/total2))*100)

        '''add new field'''
        MQ_field_name = 'acc_Mean'
        waternet.dataProvider().addAttributes([QgsField(MQ_field_name, QVariant.Double)])
        waternet.updateFields()
        features = waternet.getFeatures()

        waternet.startEditing()
        # get the index of the new field in waternet
        field_idx = waternet.fields().indexOf(MQ_field_name)
        if field_idx == -1:
            feedback.reportError(f"Error: field {MQ_field_name} not found in waternet")

        for i, feature in enumerate(features):
            # Stop the algorithm if cancel button has been clicked
            if feedback.isCanceled():
                break
            # set the value for the new field
            value_to_set = float(DataArr[i, 3])
            #feedback.setProgressText(f"Setting feature {feature.id()} field {MQ_field_name} to {value_to_set}")

            # set the new field
            feature.setAttribute(field_idx, value_to_set)
            waternet.updateFeature(feature)
        waternet.commitChanges()

        """
        Accumulate Mean Low Flow
        """
        calc_field = "M_Low_Flow"
        
        idxCalc = waternet.fields().indexFromName(calc_field)

        '''load data from layer "waternet" '''
        feedback.setProgressText(self.tr("Loading network layer\n "))
        Data = [[
            str(f.attribute(idxId)),
            str(f.attribute(idxId)),
            str(f.attribute(idxTo)),
            f.attribute(idxCalc),
            f.id()
        ] for f in waternet.getFeatures()]
        DataArr = np.array(Data, dtype='object')
        DataArr[np.where(DataArr[:,3] == None),3]=0
        feedback.setProgressText(self.tr("Data loaded \n Calculating flow paths \n"))

        '''segments with numbers'''
        calc_column = np.copy(DataArr[:,3])  # deep copy of column to do calculations on
        calc_segm = np.where(calc_column > 0)[0].tolist()  # indices!
        calc_segm = [i for i in calc_segm if (DataArr[i,1] != 'unconnected' and DataArr[i,2] != 'unconnected')]
        DataArr[:,3] = 0 # set all to 0

        total2 = len(calc_segm)
        while len(calc_segm) > 0:
            if feedback.isCanceled():
                break
            StartRow = calc_segm[0]
            amount = calc_column[StartRow] # amount to add to flow path
            calc_column[StartRow] = 0 #"delete" calculated amount from list (set 0)
            Fl_pth = FlowPath(StartRow, amount) # get flow path of StartRow 
            if len(Fl_pth)== 2:
                calc_segm = calc_segm + Fl_pth[1] # if flow path devides add new segments to calc_segm
            DataArr[Fl_pth[0],3] = DataArr[Fl_pth[0],3]+amount # Add the amount to the calculated flow path
            calc_segm = calc_segm[1:] # delete used segment
            calc_segm = list(set(calc_segm)) #delete duplicate values
            feedback.setProgress((1-(len(calc_segm)/total2))*100)

        '''add new field'''
        MNQ_field_name = 'acc_M_Low'
        waternet.dataProvider().addAttributes([QgsField(MNQ_field_name, QVariant.Double)])
        waternet.updateFields()
        features = waternet.getFeatures()

        waternet.startEditing()
        # get the index of the new field in waternet
        field_idx = waternet.fields().indexOf(MNQ_field_name)
        if field_idx == -1:
            feedback.reportError(f"Error: field {MNQ_field_name} not found in waternet")

        for i, feature in enumerate(features):
            # Stop the algorithm if cancel button has been clicked
            if feedback.isCanceled():
                break
            # set the value for the new field
            value_to_set = float(DataArr[i, 3])
            #feedback.setProgressText(f"Setting feature {feature.id()} field {MNQ_field_name} to {value_to_set}")

            # set the new field
            feature.setAttribute(field_idx, value_to_set)
            waternet.updateFeature(feature)
        waternet.commitChanges()

        # compute CATCH_TO from the river network topology (NET_ID/NET_TO → CATCH_ID mapping)
        river_to_catch = {}
        for f in river_layer_original.getFeatures():
            net_id = f["NET_ID"]
            catch_id = f["CATCH_ID"]
            if net_id is not None and catch_id is not None:
                river_to_catch[str(net_id)] = str(catch_id)

        catch_to_lookup = {}
        for f in river_layer_original.getFeatures():
            catch_id = str(f["CATCH_ID"]) if f["CATCH_ID"] is not None else None
            net_to = f["NET_TO"]
            if catch_id is None or net_to is None:
                continue
            if str(net_to) == "Out":
                catch_to_lookup.setdefault(catch_id, "Out")
            elif str(net_to) != "unconnected":
                dest_catch = river_to_catch.get(str(net_to))
                if dest_catch is not None and dest_catch != catch_id:
                    catch_to_lookup[catch_id] = dest_catch

        # define output fields with CATCH_TO inserted right after CATCH_ID
        out_fields = QgsFields()
        for field in waternet.fields():
            out_fields.append(QgsField(field.name(), field.type()))
            if field.name() == "CATCH_ID":
                out_fields.append(QgsField("CATCH_TO", QVariant.String))
        out_fields.append(QgsField("flow_unit", QVariant.String))

        # save the layer
        (sink_river, dest_id_river) = self.parameterAsSink(parameters, self.OUTPUT_river, context,
                                               out_fields, river_network.wkbType(), river_network.sourceCrs())
        
        if sink_river is None:
            raise QgsProcessingException(self.tr("Failed to create river sink"))
        
        # write features to the sink, injecting CATCH_TO value after CATCH_ID
        catch_id_idx_riv = waternet.fields().indexFromName("CATCH_ID")
        for feature in waternet.getFeatures():
            if feedback.isCanceled():
                break
            attrs = list(feature.attributes())
            cid = str(attrs[catch_id_idx_riv]) if attrs[catch_id_idx_riv] is not None else ""
            attrs.insert(catch_id_idx_riv + 1, catch_to_lookup.get(cid, "Out"))
            attrs.append('m\u00b3/s')
            out_feat = QgsFeature(out_fields)
            out_feat.setGeometry(feature.geometry())
            out_feat.setAttributes(attrs)
            sink_river.addFeature(out_feat, QgsFeatureSink.FastInsert)
        
        """
        Accumulate Mean Flow and Mean Low Flow at subcatchment level
        """
        feedback.setProgressText(self.tr("Accumulating flow at subcatchment level...\n"))

        # build ordered CATCH_ID list from the geofactors layer
        subcatch_order = []
        for f in warnow_subcatch_gf.getFeatures():
            subcatch_order.append(str(f["CATCH_ID"]))

        # fill in "Out" for any subcatchments not yet in catch_to_lookup
        for cid in subcatch_order:
            catch_to_lookup.setdefault(cid, "Out")

        for flow_field, acc_field in [("Mean_Flow", "acc_Mean"), ("M_Low_Flow", "acc_M_Low")]:
            # build per-subcatchment flow lookup from final_output
            flow_lookup = {}
            for f in final_output.getFeatures():
                cid = str(f["CATCH_ID"])
                val = f[flow_field]
                flow_lookup[cid] = val if val is not None else 0

            # build DataArr: [CATCH_ID, CATCH_ID (prev=id), CATCH_TO, flow, row_index]
            Data_catch = [[
                cid,
                cid,
                catch_to_lookup.get(cid, "Out"),
                flow_lookup.get(cid, 0),
                i
            ] for i, cid in enumerate(subcatch_order)]
            DataArr = np.array(Data_catch, dtype='object')
            DataArr[np.where(DataArr[:, 3] == None), 3] = 0

            calc_column = np.copy(DataArr[:, 3])
            calc_segm = np.where(calc_column > 0)[0].tolist()
            calc_segm = [i for i in calc_segm if DataArr[i, 2] != 'unconnected']
            DataArr[:, 3] = 0

            total2 = len(calc_segm)
            while len(calc_segm) > 0:
                if feedback.isCanceled():
                    break
                StartRow = calc_segm[0]
                amount = calc_column[StartRow]
                calc_column[StartRow] = 0
                Fl_pth = FlowPath(StartRow, amount)
                if len(Fl_pth) == 2:
                    calc_segm = calc_segm + Fl_pth[1]
                DataArr[Fl_pth[0], 3] = DataArr[Fl_pth[0], 3] + amount
                calc_segm = calc_segm[1:]
                calc_segm = list(set(calc_segm))
                feedback.setProgress(int((1 - (len(calc_segm) / total2)) * 100))

            # write accumulated values back to final_output
            final_output.startEditing()
            if acc_field not in [f.name() for f in final_output.fields()]:
                final_output.addAttribute(QgsField(acc_field, QVariant.Double))
            final_output.updateFields()
            acc_by_catch = {subcatch_order[i]: float(DataArr[i, 3]) for i in range(len(subcatch_order))}
            for feature in final_output.getFeatures():
                cid = str(feature["CATCH_ID"])
                feature.setAttribute(acc_field, acc_by_catch.get(cid, 0.0))
                final_output.updateFeature(feature)
            final_output.commitChanges()

        del nextFtsCalc, FlowPath, DataArr

        final_output_acc = final_output

        # build subcatchment output fields with CATCH_TO inserted right after CATCH_ID
        out_catch_fields = QgsFields()
        for field in final_output_acc.fields():
            out_catch_fields.append(QgsField(field.name(), field.type()))
            if field.name() == "CATCH_ID":
                out_catch_fields.append(QgsField("CATCH_TO", QVariant.String))
        out_catch_fields.append(QgsField("flow_unit", QVariant.String))

        (sink_catch, dest_id_catch) = self.parameterAsSink(parameters, self.OUTPUT_catch,
        context, out_catch_fields, warnow_subcatch_gf.wkbType(), warnow_subcatch_gf.sourceCrs())

        if sink_catch is None:
            raise QgsProcessingException(self.tr("Failed to create subcatchment sink"))

        # iterate over each subcatchment, injecting CATCH_TO after CATCH_ID
        catch_id_idx_sc = final_output_acc.fields().indexFromName("CATCH_ID")
        for feature, subcatch_feature in zip(final_output_acc.getFeatures(), warnow_subcatch_gf.getFeatures()):
            subcatch_geom = subcatch_feature.geometry()
            attrs = list(feature.attributes())
            cid = str(attrs[catch_id_idx_sc]) if attrs[catch_id_idx_sc] is not None else ""
            attrs.insert(catch_id_idx_sc + 1, catch_to_lookup.get(cid, "Out"))
            attrs.append('m\u00b3/s')
            new_feature = QgsFeature(out_catch_fields)
            new_feature.setGeometry(subcatch_geom)
            new_feature.setAttributes(attrs)
            sink_catch.addFeature(new_feature)

        
        # return the result
        return {
            self.OUTPUT_catch: dest_id_catch,
            self.OUTPUT_river: dest_id_river
            }

