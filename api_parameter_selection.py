    def propagate_substances_from_consumption(self):
        """
        Auto-propagate substances from consumption table to removal rates and PNEC tables.
        When a substance is added to consumption table:
        - Add it to removal rates table with all TC columns (empty values)
        - Add it to PNEC table with default empty structure
        When a substance is removed from consumption table:
        - Remove it from both removal rates and PNEC tables
        This ensures all three tables stay synchronized.
        """
        try:
            # Extract current API names from consumption table (from self.df)
            consumption_apis = set(self.df["API name"].unique())
            
            # Get API names from removal rates table
            removal_apis = set(self.df_RR["API name"].unique())
            
            # Get API names from PNEC tables
            era_apis = set(self.df_ERA["API name"].unique())
            hh_apis = set(self.df_HH["API name"].unique())
            amr_apis = set(self.df_AMR["API name"].unique())
            
            # APIs to add (in consumption but not in removal/PNEC)
            apis_to_add = consumption_apis - removal_apis
            
            # APIs to remove from removal rates (not in consumption anymore)
            apis_to_remove_removal = removal_apis - consumption_apis
            
            # Add missing APIs to removal rates table
            if apis_to_add:
                for api_name in apis_to_add:
                    # Create new row with all TC columns (TC1, TC2, TC3, ...)
                    new_row = {"API name": api_name}
                    # Add all TC columns from existing rows
                    if not self.df_RR.empty:
                        tc_columns = [col for col in self.df_RR.columns if col.startswith("TC") and "removal rate" in col]
                        for col in tc_columns:
                            new_row[col] = ""
                    # Add other columns that might exist
                    for col in self.df_RR.columns:
                        if col not in new_row:
                            new_row[col] = ""
                    # Append to dataframe
                    self.df_RR = pd.concat([self.df_RR, pd.DataFrame([new_row])], ignore_index=True)
            
            # Remove APIs from removal rates table
            if apis_to_remove_removal:
                self.df_RR = self.df_RR[~self.df_RR["API name"].isin(apis_to_remove_removal)].reset_index(drop=True)
            
            # Add only genuinely new APIs to all three PNEC tables
            # (use apis_to_add, not consumption - pnec, to avoid adding
            #  existing consumption substances that were never in a PNEC table)
            for df_attr, df_pnec in [("df_ERA", self.df_ERA), ("df_HH", self.df_HH), ("df_AMR", self.df_AMR)]:
                pnec_apis = set(df_pnec["API name"].unique())
                pnec_to_add = apis_to_add - pnec_apis
                if pnec_to_add:
                    for api_name in pnec_to_add:
                        new_row = {"API name": api_name}
                        for col in df_pnec.columns:
                            if col not in new_row:
                                new_row[col] = ""
                        df_pnec = pd.concat([df_pnec, pd.DataFrame([new_row])], ignore_index=True)
                    setattr(self, df_attr, df_pnec)
            
            # PNEC tables are NOT pruned — users may add PNEC-only substances
            # that don't appear in the consumption table.

            # Propagate new countries to HHRA table columns
            hh_changed = False
            if "country" in self.df.columns:
                consumption_countries = set(self.df["country"].dropna().unique())
                existing_hh_countries = set(c.strip() for c in self.df_HH.columns[1:])
                for country in consumption_countries:
                    country = country.strip()
                    if country and country not in existing_hh_countries:
                        self.df_HH[country] = ""
                        hh_changed = True
            
            # Reload tables and persist propagated changes to CSV
            if apis_to_add or apis_to_remove_removal:
                self.load_table(self.df_RR, self.RRTableView)
                self.save_temp_table(self.RRTableView, "removal_")
            if apis_to_add or hh_changed:
                self.load_table(self.df_ERA, self.ERATableView)
                self.save_temp_table(self.ERATableView, "PNEC_ERA_")
                self.load_table(self.df_HH, self.HHTableView)
                self.save_temp_table(self.HHTableView, "PNEC_HH_")
                self.load_table(self.df_AMR, self.AMRTableView)
                self.save_temp_table(self.AMRTableView, "PNEC_AMR_")
                # Refresh the country dropdown
                if hasattr(self, "CountrycomboBox"):
                    current = self.CountrycomboBox.currentText()
                    self.CountrycomboBox.clear()
                    self.CountrycomboBox.addItems([c.strip() for c in self.df_HH.columns[1:]])
                    idx = self.CountrycomboBox.findText(current)
                    if idx >= 0:
                        self.CountrycomboBox.setCurrentIndex(idx)
                
        except Exception as e:
            QMessageBox.warning(self, "Warning", f"Could not automatically propagate substances: {e}\nYou may need to manually add substances to Removal Rates and PNEC tables.")
    
    def handle_save_consumption(self):
        # Validate mandatory fields before saving
        model = self.excelTableView.model()
        if model is None:
            return
        headers = [model.headerData(col, Qt.Horizontal) for col in range(model.columnCount())]
        headers = [h.replace(' (*)', '') if h else h for h in headers]
        mandatory_fields = ["API name", "year", "country", "region", "Excreted emission (mg/inh./a)"]
        mandatory_indices = []
        for field in mandatory_fields:
            if field in headers:
                mandatory_indices.append((headers.index(field), field))

        for row in range(model.rowCount()):
            for col_idx, field_name in mandatory_indices:
                value = model.index(row, col_idx).data()
                if not value or str(value).strip() == "" or str(value).strip().lower() == "nan":
                    QMessageBox.warning(
                        self, "Missing Data",
                        f"Row {row + 1}: '{field_name}' is empty.\n\n"
                        f"Please fill in all mandatory fields\n"
                        f"(API name, year, country, region, Excreted emission)\n"
                        f"before saving."
                    )
                    return

        self.temp_consumption_path = self.save_temp_table(self.excelTableView, "consumption_")
        self.df = pd.read_csv(self.temp_consumption_path, sep=",")
        self.df.columns = [c.replace(' (*)', '') for c in self.df.columns]
        # Auto-propagate new substances to other tables
        self.propagate_substances_from_consumption()
        # Reset modification flag
        self.consumption_modified = False


    def restore_original(self, original_filename, custom_filename, loader_func, table_view):
        """
        Delete custom dataset (if it exists) and reload the original.
        """
        plugin_dir = os.path.dirname(__file__)
        custom_path = os.path.join(plugin_dir, "datasets/custom_dataset", custom_filename)
        original_path = os.path.join(plugin_dir, "datasets/original_dataset", original_filename)

        # delete custom file if it exists
        if os.path.exists(custom_path):
            os.remove(custom_path)

        # read dataframe
        temp_df = pd.read_csv(original_path, sep=",")

        # update the instance variable
        if "consumption" in original_filename.lower():
            self.df = temp_df
        elif "removal" in original_filename.lower():
            self.df_RR = temp_df
        elif original_filename == "PNEC ERA.csv":
            self.df_ERA = temp_df
        elif original_filename == "PNEC HHRA.csv":
            self.df_HH = temp_df
        elif original_filename == "PNEC AMR-RA.csv":
            self.df_AMR = temp_df

        # reload original
        loader_func(temp_df, table_view)

        QMessageBox.information(self, "Success", "Table restored to its original values.")

    
