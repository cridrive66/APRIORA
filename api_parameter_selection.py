    def _import_external_rr(self):
        """Import an external removal rates CSV and replace the current dataset."""
        import re
        from PyQt5.QtWidgets import QFileDialog
        path, _ = QFileDialog.getOpenFileName(
            self, "Import removal rate table", "", "CSV files (*.csv)"
        )
        if not path:
            return False
        try:
            df = pd.read_csv(path, sep=",")
            ok, err = self._validate_csv_columns(df, ["API name"], "removal rate")
            if not ok:
                QMessageBox.critical(self, "Invalid file", err)
                return False
            tc_cols = [c for c in df.columns
                       if re.match(r"TC\d+\s+removal rate", c, re.IGNORECASE)]
            if not tc_cols:
                QMessageBox.critical(
                    self, "Invalid file",
                    "The imported removal rate CSV must contain at least one column "
                    "matching the pattern 'TC<number> removal rate'\n"
                    "(e.g. 'TC1 removal rate', 'TC2 removal rate')."
                )
                return False

            self.df_RR = df
            plugin_dir = os.path.dirname(__file__)
            custom_dir = os.path.join(plugin_dir, "datasets/custom_dataset")
            os.makedirs(custom_dir, exist_ok=True)
            self.df_RR.to_csv(os.path.join(custom_dir, "removal_.csv"), index=False)

            self.load_table(self.df_RR, self.RRTableView)

            QMessageBox.information(
                self, "Imported",
                "Removal rate table imported successfully.\n"
                "The WWTP table will now use these removal rates."
            )
            return True
        except Exception as e:
            QMessageBox.critical(self, "Error", f"Could not import removal rate table:\n{e}")
            return False

    def closeEvent(self, event):
        """
        Override close event to prompt user to save unsaved changes before closing.
        This prevents users from accidentally losing their modifications.
        """
        modified_tabs = []
        
        # Check which tabs have unsaved changes
        if self.consumption_modified:
            modified_tabs.append(("Consumption Data (Tab 1)", self.handle_save_consumption))
        if self.removal_modified:
            modified_tabs.append(("Removal Rates (Tab 2)", self.handle_save_rr))
        if self.pnec_modified:
            modified_tabs.append(("PNEC Values (Tab 3)", self.handle_save_pnec))
        
        # If there are unsaved changes, prompt user for each tab
        if modified_tabs:
            tabs_list = "\n".join([f"  \u2022 {tab[0]}" for tab in modified_tabs])
            msg_box = QMessageBox(self)
            msg_box.setIcon(QMessageBox.Warning)
            msg_box.setWindowTitle("Unsaved Changes")
            msg_box.setText("You have unsaved changes. Do you want to save before closing?")
            msg_box.setInformativeText(tabs_list)
            msg_box.setStandardButtons(QMessageBox.Save | QMessageBox.Discard | QMessageBox.Cancel)
            msg_box.setDefaultButton(QMessageBox.Save)
            reply = msg_box.exec_()
            
            if reply == QMessageBox.Cancel:
                # Cancel close event
                event.ignore()
                return
            elif reply == QMessageBox.Save:
                # Save all modified tabs
                for tab_name, save_func in modified_tabs:
                    try:
                        save_func()
                    except Exception as e:
                        error_reply = QMessageBox.critical(
                            self,
                            "Save Error",
                            f"Failed to save {tab_name}:\n{e}\n\nDo you want to close anyway?",
                            QMessageBox.Yes | QMessageBox.No
                        )
                        if error_reply == QMessageBox.No:
                            event.ignore()
                            return
        
        # Persist field combo selections
        self.save_field_selection()
        # Allow close event to proceed
        event.accept()

