from qgis.PyQt.QtCore import QCoreApplication, QTimer
from qgis.PyQt.QtWidgets import QMessageBox
from qgis.core import (
    QgsProcessingAlgorithm,
    QgsProcessingContext
)


class APIParameterSelectionAlgorithm(QgsProcessingAlgorithm):
    """
    Processing algorithm that opens the Consumption Selection Dialog.
    This allows Tool 5 to be accessed from the Processing Toolbox.
    """

    def name(self):
        return '5 - API parameter selection'

    def displayName(self):
        return self.tr(self.name())

    def group(self):
        return self.tr(self.groupId())

    def groupId(self):
        return 'API emission'

    def shortHelpString(self):
        return self.tr("""
            This tool allows you to configure and select Active Pharmaceutical Ingredients (APIs) 
            to be used in the emission load calculations.
            
            Features:
            - Select APIs and their associated parameters from the consumption database
            - Customize consumption data, removal rates, and PNEC values
            - Create custom datasets specific to your study area
            - Configure a custom WWTP table for emission load calculations
            
            Tabs:
            1. Consumption Data - Select APIs and their consumption rates
            2. Removal Rates - Configure technical class-specific removal rates
            3. Custom Table - Create a custom WWTP table with your selected APIs
            4. PNEC Values - Set Predicted No Effect Concentrations for risk assessment
            
            IMPORTANT: This tool must be run BEFORE using the '6 - Emission Loads' tool.
            The selections made here will be used by the emission loads calculation.
        """)

    def initAlgorithm(self, config):
        """
        No parameters needed - this is a pure UI tool.
        """
        pass

    def processAlgorithm(self, parameters, context, feedback):
        """
        This method is called when the algorithm runs.
        We open the consumption dialog here.
        """
        try:
            from .consumption_selection_dialog import ConsumptionSelectionDialog
            
            # Get the main QGIS window
            from qgis.utils import iface
            
            # Create and show the dialog
            dialog = ConsumptionSelectionDialog(iface.mainWindow())
            result = dialog.exec_()
            
            feedback.pushInfo("API Parameter Selection tool opened and closed.")
            
        except Exception as e:
            feedback.reportError(f"Error opening API Parameter Selection: {str(e)}")
            import traceback
            traceback.print_exc()
        
        return {}

    def helpUrl(self):
        return "https://hosting-apriora-manual.readthedocs.io/en/latest/Consumption.html"

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def createInstance(self):
        return APIParameterSelectionAlgorithm()
